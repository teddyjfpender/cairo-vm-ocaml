#!/usr/bin/env python3
"""Generate src/hints/hint_codes.ml from cairo-vm's hint string maps.

usage: scripts/gen_hint_codes.py CAIRO_VM_CHECKOUT > src/hints/hint_codes.ml

Hints are dispatched by exact code string, so the strings are copied byte for
byte: `indoc!` raw strings get indoc's dedent, plain strings get Rust escape
and line-continuation processing. Constant names are upstream's, lowercased.
The cairo0_* table holds hints Rust only dispatches with its
`cairo-0-secp-hints` feature."""
import re, sys

START = re.compile(r'^\(([A-Z0-9_]+),\s*', re.M)
# entry end (optionally feature-gated) plus comment lines before the next entry
TAIL = r'(?:,\s*"(\w+)")?\),?\s*(?://[^\n]*\s*)*$'
RAW = re.compile(r'indoc!\s*\{r#"(.*)"#\}' + TAIL, re.S)
PLAIN = re.compile(r'"((?:[^"\\]|\\.)*)"' + TAIL, re.S)


def indoc(s):
    lines = s.split('\n')
    rest = [l for l in lines[1:] if l.strip()]
    n = min((len(l) - len(l.lstrip(' ')) for l in rest), default=0)
    return '\n'.join([lines[0]] + [l[n:] for l in lines[1:]])


def unescape(s):
    # one left-to-right pass: `\<newline>` + indentation is a continuation, `\\` a backslash
    return re.sub(r'\\(\n[ \t]*|.)', lambda m: '' if m[1][0] == '\n' else {'n': '\n', 't': '\t', '0': '\0'}.get(m[1], m[1]), s)


def table(path):
    src = open(path).read()
    start = src.index('define_hint_string_map!')
    src = src[start:start + re.compile(r'^}\s*$', re.M).search(src, start).start() - start]  # the map body only
    starts = list(START.finditer(src))
    out = []
    for m, nxt in zip(starts, starts[1:] + [None]):
        body = src[m.end():nxt.start() if nxt else len(src)]
        raw, plain = RAW.match(body), PLAIN.match(body)
        assert raw or plain, m[1]
        if (raw or plain)[2] is None:  # feature-gated entries (e.g. test_utils) are not in the default CLI
            out.append((m[1].lower(), indoc(raw[1]) if raw else unescape(plain[1])))
    return out


def emit(name, code):
    assert '|x}' not in code
    return f'let {name} = {{x|{code}|x}}'


root = sys.argv[1] + '/vm/src/hint_processor/builtin_hint_processor/'
main = table(root + 'hint_code.rs')
cairo0 = table(root + 'secp/cairo0_hints.rs')
print('(* Generated by scripts/gen_hint_codes.py from starkware-libs/cairo-vm; do not edit. *)\n')
print('\n'.join(emit(n, c) for n, c in main))
print('\nmodule Cairo0 = struct')
print('\n'.join('  ' + emit(n, c) for n, c in cairo0))
print('end')
